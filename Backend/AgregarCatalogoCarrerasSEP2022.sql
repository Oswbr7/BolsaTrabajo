/*
    Script: ampliación del catálogo dbo.RRHH_Reclutamiento_Profesiones con el
    "Catálogo de Carreras" (actualizado al 16 de mayo de 2022) que
    proporcionaste — el mismo catálogo nacional de Área de Estudio / Carrera
    Genérica / Carrera Específica.

    El PDF de origen NO trae una columna de "Nivel" (Técnico/Ingeniería/
    Licenciatura/etc. — la que sí necesita esta tabla), así que el Nivel de
    cada carrera se infirió así:
      1) Si el nombre de la carrera específica dice "Técnico"/"Técnicos" ->
         Nivel = 'Técnico'.
      2) Si no, y el nombre dice "Ingeniero"/"Ingeniería", o la carrera venía
         listada bajo el área "INGENIERIA Y TECNOLOGIA" del PDF -> Nivel =
         'Ingeniería'.
      3) Si no aplica ninguna de las anteriores -> Nivel = 'Licenciatura'
         (el resto de las áreas del PDF: Ciencias Agropecuarias, Ciencias de
         la Salud, Ciencias Naturales y Exactas, Ciencias Sociales y
         Administrativas, Educación y Humanidades).

    OJO — limitaciones conocidas de esta inferencia (el PDF de origen cruza
    la MISMA carrera específica bajo varias Áreas para clasificarla desde
    distintos ángulos, algo que esta tabla no puede representar porque el
    Nombre es único):
      - De las ~1,680 carreras específicas del PDF, ~510 eran nombres
        duplicados (la misma carrera aparecía repetida bajo más de un Área/
        Carrera Genérica) — aquí solo se agrega una vez cada nombre único
        (1,168 en total).
      - De esas, unas 76 (p. ej. "Química", "Física", "Medicina",
        "Contaduría", "Industrial", "Ecología") aparecían tanto en un área
        de Licenciatura como en "Ingeniería y Tecnología" sin decir
        "Ingeniero/Ingeniería" en el nombre — en esos casos se les asignó
        Nivel = 'Licenciatura' (por default, ya que es la más común y la
        más probable para un nombre así de genérico). Si alguna la
        necesitas como 'Ingeniería' en tu caso, dímelo y te paso un UPDATE
        aparte.
      - Bajo "Ingeniería y Tecnología" el PDF también mete de vez en cuando
        oficios de nivel Técnico sin decir la palabra "Técnico" (p. ej.
        "Electricista", "Electricista en Mecánica") — esos quedaron como
        'Ingeniería' porque no hay forma automática de distinguirlos; si
        los detectas, avísame para corregirlos con un UPDATE.
      - El PDF mismo trae algunos nombres truncados o sin acentos (p. ej.
        "Tecnico en Recreaciones Acuati" — así viene cortado en el PDF
        original) — se dejaron tal cual venían, no se adivinó el texto que
        falta.

    Motor: SQL Server (compatible con SQL Server Management Studio).
    Es seguro volver a ejecutar este script completo las veces que haga
    falta: cada INSERT solo agrega los nombres que todavía no existan
    (WHERE NOT EXISTS), igual que CrearProfesionesYCertificaciones.sql.
    Requiere que dbo.RRHH_Reclutamiento_Profesiones ya exista (créala antes
    corriendo CrearProfesionesYCertificaciones.sql si no lo has hecho).

    Uso:
      1. Conéctate en SSMS a la base de datos indicada por DB_NAME en
         Backend/.env (LUCCA).
      2. Ejecuta este script completo (F5).
      3. Revisa el mensaje final: dice cuántas carreras nuevas se agregaron
         de las 1168 de este catálogo (las demás ya existían con el
         mismo nombre, de este catálogo o del que ya tenías, y se
         saltaron).
*/

